"""Bundle the engine and one bot into a single-file CodinGame boss: config/levelK/Boss.java (class Player).

CodinGame runs a boss as one source file, so every needed class becomes a static nested class of Player.
BossFilesTest compiles each bundle and checks it plays exactly like the in-JVM bot: rerun this script after
any engine or bot change. Usage: python3 -I tools/bundle_boss.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
ENGINE = os.path.join(ROOT, "src/main/java/com/codingame/game/engine")
BOTS = os.path.join(ROOT, "src/test/java/com/codingame/game/bots")

ENGINE_FILES = ["Dir", "Optics", "Geometry", "Seats", "Board", "Beam", "BeamTracer", "Command", "CommandParser",
                "Config", "TurnReport", "Game", "MapGenerator"]
BOT_FILES = ["Bot", "Tracker", "BotState", "StrongBot"]

# level -> (bot constructor expression, description)
LEVELS = {
    1: ("new StrongBot(cfg, 1)", "StrongBot: planner, rival weight 1, hold-and-respond, two-mirror plan (V18 Wood 2 boss)"),
    2: ("new StrongBot(cfg, 2)", "StrongBot: all-lane rollout planner, horizon 3 (V18 Wood 1 boss)"),
    3: ("new StrongBot(cfg, 3)", "StrongBot: all-lane rollout planner, horizon 3, real build delay and wear (V18 Bronze boss)"),
    4: ("new StrongBot(cfg, 4)", "StrongBot: planner with rival prediction and re-planning rivals (V18 Silver boss)"),
}

MAIN = '''
    public static void main(String[] args) throws java.io.IOException {
        Config cfg = Config.forLeague(%(level)d);
        Bot bot = %(bot)s;
        java.io.BufferedReader in = new java.io.BufferedReader(new java.io.InputStreamReader(System.in));
        List<String> init = new ArrayList<>();
        String count = in.readLine();
        if (count == null) return;
        init.add(count);
        String size = in.readLine();
        init.add(size);
        for (int y = Integer.parseInt(size.trim()); y > 0; y--) init.add(in.readLine());
        bot.init(init);
        while (true) {
            List<String> turn = new ArrayList<>();
            String head = in.readLine();
            if (head == null) return;
            turn.add(head);
            readBlock(in, turn);
            readBlock(in, turn);
            System.out.println(bot.act(turn));
            System.out.flush();
        }
    }

    private static void readBlock(java.io.BufferedReader in, List<String> out) throws java.io.IOException {
        String count = in.readLine();
        out.add(count);
        for (int i = Integer.parseInt(count.trim()); i > 0; i--) out.add(in.readLine());
    }
'''


def nest(path):
    """Source of one file as a nested class: no package/imports, top-level type made static and package-private."""
    src = open(path, encoding="utf-8").read()
    imports = set(re.findall(r"^import (java\.[\w.]+(?:\.\*)?);", src, re.M))
    body = re.sub(r"^package .*?;\n", "", src, flags=re.M)
    body = re.sub(r"^import .*?;\n", "", body, flags=re.M)
    body = re.sub(r"^public (final )?(class|interface|enum) ", lambda m: "static " + (m.group(1) or "") + m.group(2) + " ",
                  body, count=1, flags=re.M)
    body = "\n".join("    " + l if l.strip() else "" for l in body.strip("\n").split("\n"))
    return imports, body


def bundle(level):
    bot, desc = LEVELS[level]
    imports, parts = {"java.util.ArrayList", "java.util.List"}, []
    for name in ENGINE_FILES:
        i, b = nest(os.path.join(ENGINE, name + ".java"))
        imports |= i
        parts.append(b)
    for name in BOT_FILES:
        i, b = nest(os.path.join(BOTS, name + ".java"))
        imports |= i
        parts.append(b)
    head = "// Glintwatch boss, league level %d: %s.\n// Generated by referee/tools/bundle_boss.py from the referee engine and bots: do not edit.\n" % (level, desc)
    text = head + "".join("import %s;\n" % i for i in sorted(imports)) + "\nclass Player { // not public: compiles as Boss.java or Player.java\n"
    text += MAIN % {"level": level, "bot": bot} + "\n" + "\n\n".join(parts) + "\n}\n"
    return text


def main():
    for level in LEVELS:
        path = os.path.join(ROOT, "config", "level%d" % level, "Boss.java")
        with open(path, "w", encoding="utf-8") as f:
            f.write(bundle(level))
        old = os.path.join(ROOT, "config", "level%d" % level, "Boss.py")
        if os.path.exists(old):
            os.remove(old)
        print(path, os.path.getsize(path), "bytes")


if __name__ == "__main__":
    main()
